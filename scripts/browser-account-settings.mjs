import assert from 'node:assert/strict';
import { resolve } from 'node:path';

export async function verifyAccountSettings(page, context, origin, detailURL, output) {
  const detail = new URL(detailURL);
  const pid = detail.searchParams.get('projectId') ?? detail.pathname.match(/^\/projects\/(\d+)/)?.[1];
  assert(pid, 'project identifier is required');
  await page.goto(`${origin}/projects/settings/?projectId=${pid}`);
  await page.getByRole('button', { name: '修改项目名称', exact: true }).click();
  await page.getByLabel('项目名称', { exact: true }).fill('Browser renamed project');
  await page.getByRole('button', { name: '保存项目名称', exact: true }).click();
  await page.getByRole('button').filter({ hasText: 'Browser renamed project' }).waitFor({ state: 'visible' });
  await page.reload();
  await page.getByRole('button', { name: '修改项目名称', exact: true }).click();
  assert.equal(await page.getByLabel('项目名称', { exact: true }).inputValue(), 'Browser renamed project');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.screenshot({ path: resolve(output, 'project-settings.png'), fullPage: true });
  await page.getByRole('button', { name: /admin@example.com/ }).click();
  await page.getByRole('menuitem', { name: '个人中心', exact: true }).click();
  assert.equal(await page.getByRole('table').count(), 0, 'profile must not contain account or team tables');
  assert.equal(await page.locator('input').count(), 0, 'profile must not contain inline forms');
  await page.getByRole('button', { name: '修改显示名称', exact: true }).click();
  await page.getByLabel('显示名称', { exact: true }).fill('Browser renamed user');
  await page.getByLabel('显示名称', { exact: true }).press('Enter');
  await page.getByRole('button', { name: /Browser renamed user.*admin@example.com/ }).waitFor({ state: 'visible' });
  await page.reload();
  await page.getByRole('button', { name: '修改显示名称', exact: true }).click();
  assert.equal(await page.getByLabel('显示名称', { exact: true }).inputValue(), 'Browser renamed user');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.screenshot({ path: resolve(output, 'profile-overview.png'), fullPage: true });
  await page.getByRole('button', { name: '修改密码', exact: true }).click();
  await page.getByLabel('原密码', { exact: true }).fill('cancelled-test-input');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByRole('button', { name: '修改密码', exact: true }).click();
  for (const label of ['原密码', '新密码', '确认新密码']) assert.equal(await page.getByLabel(label, {exact:true}).inputValue(), '');
  await page.getByLabel('原密码', { exact: true }).fill('wrong');
  await page.getByLabel('新密码', { exact: true }).fill('Browser-new-password');
  await page.getByLabel('确认新密码', { exact: true }).fill('different-password');
  await page.getByRole('button', { name: '确认修改', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '两次输入的新密码不一致。' }).waitFor({ state: 'visible' });
  await page.getByLabel('确认新密码', { exact: true }).fill('Browser-new-password');
  await page.getByRole('button', { name: '确认修改', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '原密码不正确，请重新输入。' }).waitFor({ state: 'visible' });
  await page.screenshot({ path: resolve(output, 'profile-settings.png'), fullPage: true });
  const other = await context.browser().newContext({ ignoreHTTPSErrors: true });
  try {
    const token = (await (await other.request.get(`${origin}/api/auth/csrf`)).json()).csrfToken;
    const login = await other.request.post(`${origin}/api/auth/login`, { headers: { Origin: origin, 'X-CSRF-Token': token }, data: { username: 'admin@example.com', password: 'admin' } });
    assert.equal(login.status(), 200);
    await page.getByLabel('原密码', { exact: true }).fill('admin');
    await page.getByRole('button', { name: '确认修改', exact: true }).click();
    await page.waitForURL(url => /^\/login\/?$/.test(url.pathname));
    assert.equal((await other.request.get(`${origin}/api/auth/session`)).status(), 401);
    assert.equal((await context.request.get(`${origin}/api/auth/session`)).status(), 401);
    await page.getByLabel('邮箱或手机号').fill('admin@example.com');
    await page.getByLabel('密码', { exact: true }).fill('admin');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.getByText('邮箱、手机号或密码错误', { exact: false }).waitFor({ state: 'visible' });
    await page.getByLabel('邮箱或手机号').fill('admin@example.com');
    await page.getByLabel('密码', { exact: true }).fill('Browser-new-password');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.waitForURL(url => /^\/projects\/?$/.test(url.pathname));
    await page.getByRole('link', { name: /Browser renamed project/ }).waitFor({ state: 'visible' });
  } finally { await other.close(); }
  return { passed: true, checks: ['project name modal and sidebar refresh', 'display name modal and sidebar refresh', 'single account overview without tables or inline forms', 'password modal cancel and input clearing', 'Enter submission', 'password confirmation mismatch', 'wrong current password', 'multi-client session revocation', 'old password rejection', 'new password login'] };
}
